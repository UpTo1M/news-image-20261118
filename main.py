"""Entry point for the news-image-20261118 competition.

Copies the pre-built 1024x1024 front-page image (entry.png, generated by
draw.py with PIL at build time and committed next to this script) to
<output_dir>/entry.png, where output_dir comes from the
MAKEFUN_OUTPUT_DIR environment variable (default "/output").

Standard library only: the grader runs this with "standard library only:
nothing is installed before it runs", so this script must not import PIL
or draw.py. The bot directory is mounted read-only by the grader, so this
script never writes to it. Deterministic: a file copy is byte-identical.
No network, no randomness, no timestamps.
"""

import os
import shutil

_HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    src = os.path.join(_HERE, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, out_path)
    print("wrote", out_path)


if __name__ == "__main__":
    main()
